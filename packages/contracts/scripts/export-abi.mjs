// Regenerates packages/shared/src/abis.generated.ts from the compiled artifacts.
// Usage: pnpm --filter @hive/contracts abi   (or: node scripts/export-abi.mjs)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const contractsRoot = resolve(here, "..");
const sharedSrc = resolve(contractsRoot, "../shared/src");

const contracts = [
  ["AgentRegistry", "AgentRegistry"],
  ["KnowledgeGraph", "KnowledgeGraph"],
  ["MemorySlots", "MemorySlots"],
  ["PropagationEngine", "PropagationEngine"],
];

function runForge(args) {
  try {
    execFileSync("forge", args, { cwd: contractsRoot, stdio: "inherit" });
  } catch (err) {
    console.error("Failed to run `forge build`. Is Foundry (>= 1.8) on your PATH?");
    throw err;
  }
}

runForge(["build"]);

const lines = [
  "// Auto-generated by packages/contracts/scripts/export-abi.mjs — do not edit.",
  "// Regenerate with: pnpm --filter @hive/contracts abi",
  "",
];

for (const [name, contract] of contracts) {
  const artifactPath = join(contractsRoot, "out", `${contract}.sol`, `${contract}.json`);
  if (!existsSync(artifactPath)) {
    throw new Error(`Missing artifact ${artifactPath}. Run \`forge build\` first.`);
  }
  const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
  lines.push(`export const ${name}Abi = ${JSON.stringify(artifact.abi)} as const;`);
  lines.push("");
}

mkdirSync(sharedSrc, { recursive: true });
const outPath = join(sharedSrc, "abis.generated.ts");
writeFileSync(outPath, lines.join("\n"));
console.log(`Wrote ${contracts.length} ABIs to ${outPath}`);

